# Ruby is dynamically typed: no type is written when declaring a variable

my_string = "Ruby"
my_num = 25
my_float = 3.14
my_bool = true
my_nil = nil
my_array = [1, 2, 3]
my_hash = { "language" => "Ruby" }
my_symbol = :ruby

puts my_num
puts my_bool
puts my_string
puts my_float

p my_nil
p my_array
p my_hash
p my_symbol
